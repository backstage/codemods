#!/usr/bin/env bash
# Called after yarn readme and validation on a clean checkout of main.
set -euo pipefail

branch=automation/readme-sync
subject='docs: sync generated README'
bot_email='41898282+github-actions[bot]@users.noreply.github.com'

changed=$(git diff --name-only HEAD)
if [ -z "$changed" ]; then
  echo 'README is current; no branch or PR changes.'
  exit 0
fi
if [ "$changed" != README.md ] || ! git diff --cached --quiet; then
  echo 'Expected only an unstaged generated README.md change.' >&2
  exit 1
fi

generated=$(mktemp)
trap 'rm -f "$generated"' EXIT
cp README.md "$generated"
git restore -- README.md
git fetch origin --prune
if [ "$(git rev-parse HEAD)" != "$(git rev-parse origin/main)" ]; then
  echo 'main advanced during generation; rerun the workflow.' >&2
  exit 1
fi

# Refuse a branch or PR not owned by this workflow; never force-push.
open_pr=$(gh pr list --head "$branch" --base main --state open --json number,author --jq '.[] | "\(.number) \(.author.login)"')
if [ -n "$open_pr" ] && [[ ! "$open_pr" =~ ^[0-9]+\ github-actions\[bot\]$ ]]; then
  echo "Unexpected open PR for $branch: $open_pr" >&2
  exit 1
fi
if git show-ref --verify --quiet "refs/remotes/origin/$branch"; then
  branch_diff=$(git diff --name-only "$(git merge-base origin/main "origin/$branch")" "origin/$branch")
  if [ "$(git log -1 --format=%ae "origin/$branch")" != "$bot_email" ] ||
    [ "$(git log -1 --format=%s "origin/$branch")" != "$subject" ] ||
    { [ "$branch_diff" != README.md ] &&
      { [ -n "$branch_diff" ] || ! git merge-base --is-ancestor "origin/$branch" origin/main; }; }; then
    echo "Refusing to update unrecognized branch $branch." >&2
    exit 1
  fi
  git switch -c "$branch" "origin/$branch"
  git -c user.name='github-actions[bot]' -c user.email="$bot_email" merge -m "$subject" origin/main # Conflict stops without pushing.
else
  if [ -n "$open_pr" ]; then
    echo "Open PR exists but $branch does not; refusing to replace it." >&2
    exit 1
  fi
  git switch -c "$branch"
fi

cp "$generated" README.md
if ! git diff --quiet -- README.md; then
  git add README.md
  git -c user.name='github-actions[bot]' -c user.email="$bot_email" commit -m "$subject"
fi
git push origin "HEAD:refs/heads/$branch"

if [ -z "$open_pr" ]; then
  gh pr create --base main --head "$branch" --title "$subject" --body 'Generated by the manual **Sync codemod README** workflow on main. Review the README diff before merging. The workflow runs format, tests, script regressions, and README idempotence checks before pushing; it does not run repository-wide lint. PRs created with GITHUB_TOKEN do not trigger pull_request CI; inspect the successful dispatch run rather than assuming CI ran on this PR.'
else
  echo "Updated existing bot PR #${open_pr%% *}."
fi
