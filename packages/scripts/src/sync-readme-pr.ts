#!/usr/bin/env node
import { copyFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

// Called after yarn readme and validation on a clean checkout of main.
// Creates or updates the automation/readme-sync branch and its bot PR.
import { cli } from 'cleye'

import { exitOnFailure, runGh, runGit } from './lib/spawn.ts'

cli({ name: 'sync-readme-pr' })

const branch = 'automation/readme-sync'
const subject = 'docs: sync generated README'
const botEmail = '41898282+github-actions[bot]@users.noreply.github.com'

function gitOutput(args: string[]): string {
  return runGit(args, { capture: true }).stdout.replace(/\n$/, '')
}

function gitOk(args: string[]): boolean {
  return runGit(args, { capture: true }).status === 0
}

function ghOutput(args: string[]): string {
  const result = runGh(args, { capture: true })
  if (result.status !== 0) {
    console.error(result.stderr)
    process.exit(result.status ?? 1)
  }
  return result.stdout.replace(/\n$/, '')
}

function fail(message: string): never {
  console.error(message)
  process.exit(1)
}

const changed = gitOutput(['diff', '--name-only', 'HEAD'])
  .split('\n')
  .filter((line) => line !== '')
if (changed.length === 0) {
  console.log('README is current; no branch or PR changes.')
  process.exit(0)
}
if (changed.length !== 1 || changed[0] !== 'README.md' || gitOk(['diff', '--cached', '--quiet'])) {
  fail('Expected only an unstaged generated README.md change.')
}

const generated = join(tmpdir(), `generated-readme-${process.pid}.md`)
copyFileSync('README.md', generated)
exitOnFailure(runGit(['restore', '--', 'README.md']))
exitOnFailure(runGit(['fetch', 'origin', '--prune']))
if (gitOutput(['rev-parse', 'HEAD']) !== gitOutput(['rev-parse', 'origin/main'])) {
  fail('main advanced during generation; rerun the workflow.')
}

// Refuse a branch or PR not owned by this workflow; never force-push.
const openPr = ghOutput([
  'pr',
  'list',
  '--head',
  branch,
  '--base',
  'main',
  '--state',
  'open',
  '--json',
  'number,author',
  '--jq',
  '.[] | "\\(.number) \\(.author.login)"',
])
if (openPr !== '' && !/^[0-9]+ github-actions\[bot\]$/.test(openPr)) {
  fail(`Unexpected open PR for ${branch}: ${openPr}`)
}

const gitBot = ['-c', 'user.name=github-actions[bot]', `-c`, `user.email=${botEmail}`]
if (gitOk(['show-ref', '--verify', '--quiet', `refs/remotes/origin/${branch}`])) {
  const branchDiff = gitOutput([
    'diff',
    '--name-only',
    gitOutput(['merge-base', 'origin/main', `origin/${branch}`]),
    `origin/${branch}`,
  ])
  const ancestor = gitOk(['merge-base', '--is-ancestor', `origin/${branch}`, 'origin/main'])
  const recognized =
    gitOutput(['log', '-1', '--format=%ae', `origin/${branch}`]) === botEmail &&
    gitOutput(['log', '-1', '--format=%s', `origin/${branch}`]) === subject &&
    (branchDiff === 'README.md' || (branchDiff === '' && ancestor))
  if (!recognized) {
    fail(`Refusing to update unrecognized branch ${branch}.`)
  }
  exitOnFailure(runGit(['switch', '-c', branch, `origin/${branch}`]))
  // A conflict stops without pushing.
  exitOnFailure(runGit([...gitBot, 'merge', '-m', subject, 'origin/main']))
} else {
  if (openPr !== '') {
    fail(`Open PR exists but ${branch} does not; refusing to replace it.`)
  }
  exitOnFailure(runGit(['switch', '-c', branch]))
}

copyFileSync(generated, 'README.md')
if (!gitOk(['diff', '--quiet', '--', 'README.md'])) {
  exitOnFailure(runGit(['add', 'README.md']))
  exitOnFailure(runGit([...gitBot, 'commit', '-m', subject]))
}
exitOnFailure(runGit(['push', 'origin', `HEAD:refs/heads/${branch}`]))

if (openPr === '') {
  exitOnFailure(
    runGh([
      'pr',
      'create',
      '--base',
      'main',
      '--head',
      branch,
      '--title',
      subject,
      '--body',
      'Generated by the manual **Sync codemod README** workflow on main. Review the README diff before merging. The workflow runs format, tests, script regressions, and README idempotence checks before pushing; it does not run repository-wide lint. PRs created with GITHUB_TOKEN do not trigger pull_request CI; inspect the successful dispatch run rather than assuming CI ran on this PR.',
    ]),
  )
} else {
  console.log(`Updated existing bot PR #${openPr.split(' ')[0]}.`)
}
